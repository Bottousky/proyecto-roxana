import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const url = process.env.ARITHMOS_URL || 'http://127.0.0.1:5197/arithmos/';
const out = 'output/arithmos-touch';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const state = () => page.evaluate(() => window.__arithmos.state);
const visible = name => page.locator(`[data-do="${name}"]`).filter({ visible: true });
async function tap(name) { await visible(name).tap(); }
try {
  await page.goto(url); await page.waitForFunction(() => Boolean(window.__arithmos));
  await tap('start'); await tap('quiet');
  await page.waitForTimeout(1200);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'no horizontal overflow');
  await page.screenshot({ path: `${out}/01-portrait.png` });
  const first = await page.evaluate(() => window.__arithmos.project(-1, 3));
  assert.ok(Number.isFinite(first.x) && Number.isFinite(first.y), `finite touch target: ${JSON.stringify(first)}`);
  await page.touchscreen.tap(first.x, first.y);
  assert.equal((await state()).selected, 'landing-cloth', 'touch picks actual matter');
  await tap('zoom-in'); await tap('zoom-in'); await tap('zoom-in');
  await page.screenshot({ path: `${out}/02-manipulation.png` });
  await tap('widen');
  for (let i = 0; i < 5; i++) await tap('move-up');
  assert.equal((await state()).evaluation.solved, true, 'touch transformed and placed bridge');
  await tap('recenter'); await tap('deselect'); await tap('quiet');
  await tap('next'); await tap('quiet');
  const origin = await page.evaluate(() => window.__arithmos.project(-2, 3));
  await page.touchscreen.tap(origin.x, origin.y);
  await tap('cut'); await page.locator('[data-cell="6"]').tap();
  assert.equal((await state()).board.pieces.length, 1, 'touch first previews the cut');
  assert.equal(await page.locator('.ari-unit.ari-cut-stay').count(), 6);
  assert.equal(await page.locator('.ari-unit.ari-cut-away').count(), 6);
  await page.screenshot({ path: `${out}/02b-cut-preview.png` });
  await tap('cut-apply');
  assert.equal((await state()).board.pieces.length, 2);
  await tap('join'); await tap('cycle');
  assert.equal((await state()).board.pieces.length, 1, 'touch reunites split matter');
  await tap('undo'); assert.equal((await state()).board.pieces.length, 2);
  await tap('redo'); assert.equal((await state()).board.pieces.length, 1);
  await tap('narrow'); await tap('narrow');
  assert.equal((await state()).board.pieces[0].width, 2);
  await tap('cut');
  await page.locator('[data-cell="10"]').tap();
  assert.equal((await state()).cutAt, 10, 'the last row of a tall piece is selectable');
  assert.equal(await page.locator('.ari-preview-scroll').isVisible(), true, 'tall pieces advertise scrolling');
  await page.screenshot({ path: `${out}/03a-tall-piece-cut.png` });
  await tap('cut');
  assert.equal((await state()).cutAt, null, 'cancel clears the candidate');
  await tap('lens');
  await page.screenshot({ path: `${out}/03-plan-lens.png` });
  await page.setViewportSize({ width: 844, height: 390 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight && document.documentElement.scrollWidth <= innerWidth), true, 'landscape has no document overflow');
  await tap('move-left');
  await tap('cut');
  await page.locator('[data-cell="0"]').tap();
  assert.equal(await visible('cut-apply').isDisabled(), true, 'the first unit cannot leave an empty piece');
  await page.locator('[data-cell="6"]').tap();
  const targetSize = await page.locator('[data-cell="6"]').boundingBox();
  assert.ok(targetSize.width >= 44 && targetSize.height >= 44, 'cut targets stay touch sized in landscape');
  await page.screenshot({ path: `${out}/04b-landscape-cut.png` });
  await tap('cut-apply'); await tap('undo');
  await page.screenshot({ path: `${out}/04-landscape.png` });
  await tap('menu'); await page.locator('dialog [data-do="sound"]').tap();
  assert.equal(await page.locator('dialog [data-do="sound"]').textContent(), 'Activar sonido');
  await page.locator('dialog [data-do="motion"]').tap();
  assert.equal(await page.locator('dialog [data-do="motion"]').textContent(), 'Reducir movimiento', 'the player can override the device motion preference');
  await page.locator('dialog [data-do="close"]').filter({ visible: true }).last().tap();
  await page.reload(); await page.waitForFunction(() => Boolean(window.__arithmos)); await tap('start');
  assert.equal((await state()).restored.length, 1);
  await tap('menu');
  assert.equal(await page.locator('dialog [data-do="sound"]').textContent(), 'Activar sonido', 'mute survives reload');
  assert.equal(await page.locator('dialog [data-do="motion"]').textContent(), 'Reducir movimiento', 'explicit motion preference survives reload');
  assert.equal(errors.length, 0, errors.join('\n'));
  await writeFile(`${out}/result.json`, JSON.stringify({ result: 'PASS', errors, viewport: [390, 844], checks: ['real touch selection', 'zoom', 'shape and placement', 'split and join', 'undo redo', 'lens', 'rotation viewport', 'mute persistence', 'restoration persistence'] }, null, 2));
  console.log('PASS: touch and responsive interaction.');
} catch (error) {
  await page.screenshot({ path: `${out}/failure.png` }).catch(() => {});
  await writeFile(`${out}/result.json`, JSON.stringify({ result: 'FAIL', errors, error: String(error), state: await state().catch(() => null) }, null, 2));
  console.error(error); process.exitCode = 1;
} finally { await browser.close(); }
